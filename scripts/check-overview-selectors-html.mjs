import { chromium, expect } from '@playwright/test'
import { readFile, mkdir } from 'node:fs/promises'
import { resolve } from 'node:path'
const html=await readFile(resolve(process.argv[2] || 'exports/zonhack-demo.html'),'utf8')
const screenshotDir = resolve(process.env.DEMO_SCREENSHOT_DIR || 'test-results/standalone-selectors')
await mkdir(screenshotDir, { recursive: true })
const browser=await chromium.launch({executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE || undefined,headless:true})
try {
 const context=await browser.newContext({offline:true,viewport:{width:1257,height:850}})
 await context.addInitScript(()=>localStorage.setItem('zonhack:demo:appearance',JSON.stringify({theme:'dark',collapsed:false,home:'overview',density:'comfortable'})))
 const page=await context.newPage(),errors=[],external=[]
 page.on('pageerror',error=>errors.push(error.message))
 await context.route('**/*',async route=>{if(route.request().url()==='http://127.0.0.1:3117/zonhack-demo.html')await route.fulfill({contentType:'text/html',body:html});else{external.push(route.request().url());await route.abort()}})
 await page.goto('http://127.0.0.1:3117/zonhack-demo.html')
 await expect(page.locator('.year-chart')).toHaveCount(6)
 await expect(page.locator('html')).toHaveAttribute('data-theme','dark')
 await expect(page.locator('canvas').first()).toBeVisible()
 await expect(page.getByRole('button',{name:'Select marketplace',exact:true})).toContainText('All marketplaces')
 await expect(page.getByRole('button',{name:'Select SKU',exact:true})).toContainText('All SKUs')
 await page.screenshot({path:resolve(screenshotDir, 'zonhack-marketplace-sku-preview.png'),fullPage:false})
 await page.getByRole('button',{name:'Select marketplace',exact:true}).click()
 await expect(page.getByRole('region',{name:'Marketplace selection'})).toBeVisible()
 await expect(page.getByRole('button',{name:'All marketplaces',exact:true})).toBeVisible()
 await page.screenshot({path:resolve(screenshotDir, 'zonhack-marketplace-menu.png'),fullPage:false})
 await page.keyboard.press('Escape')
 await page.getByRole('button',{name:'Select SKU',exact:true}).click()
 await page.getByRole('button',{name:'Parent SKU',exact:true}).click()
 await expect(page.getByRole('button',{name:'Choose parent SKU CARRY-PARENT',exact:true})).toContainText('2 child variations')
 await page.screenshot({path:resolve(screenshotDir, 'zonhack-sku-menu.png'),fullPage:false})
 await page.getByRole('button',{name:'Choose parent SKU CARRY-PARENT',exact:true}).click()
 await expect(page.getByRole('button',{name:'Select SKU',exact:true})).toContainText('CARRY-PARENT')
 await page.getByRole('button',{name:'Select marketplace',exact:true}).click()
 await page.getByRole('button',{name:'Canada',exact:true}).click()
 await expect(page.getByRole('button',{name:'Select marketplace',exact:true})).toContainText('Canada')
 await expect(page.locator('.year-chart-unit').first()).toHaveText('CAD')
 await page.getByRole('button',{name:'Select SKU',exact:true}).click()
 await page.getByRole('button',{name:'Single SKU',exact:true}).click()
 await page.getByRole('textbox',{name:'Search SKUs',exact:true}).fill('TOTE-OLIVE')
 await page.getByRole('button',{name:'Choose SKU TOTE-OLIVE',exact:true}).click()
 await expect(page.getByRole('button',{name:'Select SKU',exact:true})).toContainText('TOTE-OLIVE')
 await page.reload()
 await expect(page.getByRole('button',{name:'Select SKU',exact:true})).toContainText('TOTE-OLIVE')
 await expect(page.getByRole('button',{name:'Select marketplace',exact:true})).toContainText('Canada')
 await page.setViewportSize({width:390,height:844})
 await page.getByRole('button',{name:'Select marketplace',exact:true}).click()
 await expect(page.getByRole('region',{name:'Marketplace selection'})).toBeInViewport()
 if(!await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))throw new Error('Mobile scope menu overflow')
 if(errors.length||external.length)throw new Error(JSON.stringify({errors,external}))
 console.log('PASS: offline dark-theme marketplace/SKU menus, all markets, parent/single choices, currency update, persistence, mobile menu. Zero external requests or page errors.')
}finally{await browser.close()}
